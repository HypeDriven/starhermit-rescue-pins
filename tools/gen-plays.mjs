// Writes the native play scripts (tests/native/*.play) from the rules: each
// stage's winning pull order comes from rules.js's solver, and the script
// plays it through the real UI — by keys (the selection starts on the first
// pin you can pull; → moves it; Enter pulls), by finger on the brass pins'
// named targets (a first touch selects, a second pulls), or by the status
// rail's pin buttons (one press pulls). tests/native.mjs also calls
// dailyScript() at test time for the day's Daily.
//   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { applyCommand, createInitialState, makeStreams, solveLevel } from '../js/rules.js';
import { getJourney, getTutorial } from '../js/content.js';

const STARTED = ['until 300 Pins you can pull', 'frames 100'];
const RESULTS = (won) => ['until 600 Pins pulled:', `expect ${won ? 'Rescued!' : 'The castle claims another'}`, 'frames 10'];

function solution(level) {
  const r = solveLevel(level);
  if (!r.solvable) throw new Error(`${level.id} unsolvable`);
  return r.solution;
}
/** Keys: → to the pin (from the first pin you can pull), Enter. */
export function byKeys(level, order) {
  const out = [];
  let s = createInitialState(level, makeStreams(level.seed));
  for (const id of order) {
    const i = s.pins.findIndex((p) => p.id === id);
    out.push(`# pull ${id}`);
    for (let k = 0; k < i; k++) out.push('key ArrowRight 1', 'frames 2');
    out.push('key Enter 1', 'frames 20');
    s = applyCommand(s, { type: 'pull', pinId: id }).state;
  }
  return out;
}
/**
 * A finger on the pin's named target: a touch on the selected pin pulls it, on another selects it
 * (the selection starts, and after each pull returns, on the first pin you can pull).
 */
export function byTouch(level, order, verb = 'touch') {
  const out = [];
  let s = createInitialState(level, makeStreams(level.seed));
  for (const id of order) {
    out.push(`# pull ${id}`);
    if (s.pins[0].id !== id) out.push(`${verb} Brass pin ${id}`, 'frames 10');
    out.push(`${verb} Brass pin ${id}`, 'frames 20');
    s = applyCommand(s, { type: 'pull', pinId: id }).state;
  }
  return out;
}
/** The status rail's buttons: one press pulls. */
export function byList(order, verb = 'click') {
  return order.flatMap((id) => [`# pull ${id}`, `${verb} =Pin ${id}`, 'frames 20']);
}

/** The Daily for a level definition (desktop, the rail's pin buttons). */
export function dailyScript(level) {
  return [
    `# Generated at test time by tests/native.mjs (tools/gen-plays.mjs dailyScript): ${level.id}, played by the rail's pin buttons.`,
    '# viewport 1280x800@1',
    'until 600 Daily Challenge', 'frames 30',
    'click =Daily Challenge',
    ...STARTED, 'save daily-castle',
    ...byList(solution(level)),
    ...RESULTS(true), 'expect Daily score kept locally.', 'save daily-results',
  ].join('\n') + '\n';
}

const header = (what, vp) => [`# Generated by tools/gen-plays.mjs: ${what}`, `# viewport ${vp}`];

function journeyKeys() {
  const J = getJourney();
  const lines = [...header('Journey stages 1-8 on a desktop by keys (→ chooses, Enter pulls), each played to its results; stage 6 has a move limit, 7 brings lava.', '1280x800@1'),
    'until 600 Daily Challenge', 'frames 30', 'click =Journey', 'until 300 ☆ 1', 'frames 10', 'click Emerald Keep 1 —'];
  for (let i = 0; i < 8; i++) {
    const lv = J[i];
    lines.push(`# ${lv.id} ${lv.name}`, ...STARTED);
    if (i === 6) lines.push('save journey-7');
    lines.push(...byKeys(lv, solution(lv)), ...RESULTS(true));
    if (i === 6) lines.push('save journey-7-results');
    if (i < 7) lines.push('click =Next stage');
  }
  lines.push('click =Menu', 'until 300 Journey progress: 8/40', 'save title-progress');
  return lines.join('\n') + '\n';
}

function learnPhone() {
  const tut = getTutorial();
  const lines = [...header('the five Learn lessons on a DPR-3 phone by finger (a touch on a brass pin selects it, a second pulls it); lesson 3 is first lost by pulling the lower pin, then retried.', '390x844@3'),
    'until 600 Daily Challenge', 'frames 30', 'touch =▶ Play', 'until 300 Choose a mode', 'frames 10', 'touch =Learn'];
  tut.forEach((l, i) => {
    lines.push(`# ${l.id} ${l.title}`, ...STARTED);
    if (i === 0) lines.push('save lesson-1');
    if (l.id === 'tut-3') {
      lines.push(...byTouch(l.level, ['pb']), ...RESULTS(false), 'expect Lava reached a villager.', 'save lesson-3-lost', 'touch =Retry', ...STARTED);
    }
    lines.push(...byTouch(l.level, solution(l.level)), ...RESULTS(true));
    if (i === 4) lines.push('save lesson-5-results');
    lines.push('touch =Next stage');
  });
  lines.push('until 300 Daily Challenge', 'touch =Profile & Progress', 'until 300 Tutorial: complete', 'expect ✓ Mechanic Mastery', 'save profile');
  return lines.join('\n') + '\n';
}

function practiceLand() {
  const J = getJourney();
  const lv = J[8];
  const order = solution(lv);
  const wrong = lv.pins.map((p) => p.id).find((id) => {
    const s = applyCommand(createInitialState(lv, makeStreams(lv.seed)), { type: 'pull', pinId: id }).state;
    return s.status === 'active' && !order.includes(id);
  });
  const lines = [...header(`Practice on a phone held sideways (DPR 3): ${lv.id} ${lv.name} — a pull off the winning line (${wrong}), Undo, the Hint, then the winning pulls from the rail's pin buttons.`, '844x390@3'),
    'until 600 Daily Challenge', 'frames 30', 'touch =▶ Play', 'until 300 Choose a mode', 'frames 10', 'touch =Practice',
    'until 300 ☆ 9', 'frames 10', `touch ${lv.name} —`, ...STARTED,
    ...byList([wrong], 'touch'), 'until 120 ↩ Undo (U)', 'save practice-undo', 'touch =↩ Undo (U)', 'frames 20',
    'touch =💡 Hint (H)', `until 600 Try pin ${order[0]}`, 'frames 5', 'save practice-hint',
    ...byList(order, 'touch'), ...RESULTS(true), 'save practice-results'];
  return lines.join('\n') + '\n';
}

function menus() {
  const J = getJourney();
  const lv = J[1];
  const order = solution(lv);
  const lines = [...header('the menus on a desktop: How to play, Settings (the colorblind palette, captions), Profile; a Journey stage paused (rule cards from the pause panel), saved and quit, continued from the title and won.', '1280x800@1'),
    'until 600 Daily Challenge', 'frames 30',
    'click =How to play', 'until 300 Water rescues', 'save help', 'click =Back',
    'until 300 Daily Challenge', 'frames 10', 'click =⚙ Settings', 'until 300 Accessibility', 'frames 10',
    'click =Default', 'frames 10', 'click =Colorblind', 'frames 10', 'save settings', 'click =Back',
    'until 300 Daily Challenge', 'frames 10', 'click =Profile & Progress', 'until 300 Stages cleared: 0/40', 'click =Back',
    'until 300 Daily Challenge', 'frames 10', 'click =Journey', 'until 300 ☆ 2', 'frames 10', 'click Emerald Keep 2 —', ...STARTED,
    'save palette-colorblind',
    'key Escape 1', 'until 300 Resume', 'frames 10', 'save pause', 'click =Rule cards', 'until 300 Lava kills', 'click =Back',
    'until 300 Resume', 'frames 10', 'click =Save & quit to title', 'until 300 Continue saved game', 'frames 10',
    'click =Continue saved game', 'until 300 Pins you can pull', 'frames 30',
    ...byList(order), ...RESULTS(true)];
  return lines.join('\n') + '\n';
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const out = { 'journey-keys.play': journeyKeys(), 'learn-phone.play': learnPhone(), 'practice-land.play': practiceLand(), 'menus.play': menus() };
  for (const [f, text] of Object.entries(out)) writeFileSync(new URL(`../tests/native/${f}`, import.meta.url), text);
  console.log(`wrote ${Object.keys(out).join(', ')}`);
}
