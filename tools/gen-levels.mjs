// Writes js/journey.js: the 40 Journey stages as js/content.js's generator
// builds them (the solver-verified, deterministic recipe). The generator runs
// ~1 s in V8 and far longer in the engine's interpreter, so the game ships
// its output; tests/content.test.js checks the table still matches.
//   node tools/gen-levels.mjs
import { writeFileSync } from 'node:fs';
import { generateJourney } from '../js/content.js';

const levels = generateJourney();
const body = levels.map((l) => '  ' + JSON.stringify(l)).join(',\n');
writeFileSync(new URL('../js/journey.js', import.meta.url),
  `// Generated by tools/gen-levels.mjs from js/content.js's journey generator — do not edit.\nexport const JOURNEY = [\n${body},\n];\n`);
console.log(`wrote js/journey.js (${levels.length} stages)`);
